    <div class="abtb_doc_page_head">
        <h2>✂️ Discount Configuration (PRO)</h2>
        <p class="abtb_doc_lede">
            The Discount system lets you configure transport-specific Seasonal Discounts and Early Bird Discounts. Define multiple date ranges and discount percentages for each type to control promotional and advance-booking pricing on a per-transport basis.
        </p>
    </div>

    <h3>🌤️ Seasonal Discount</h3>
    <p class="abtb_doc_section_intro">
        Seasonal discounts apply reduced pricing during specific date ranges — for example, holiday periods or off-peak seasons. You can define one or more seasonal periods per transport.
    </p>
    <ul>
        <li>Enable or disable Seasonal Discount for the transport.</li>
        <li>Define a start and end date for each seasonal discount period.</li>
        <li>Set the discount percentage for each seasonal date range.</li>
        <li>Add multiple seasonal date ranges when different periods require different discounts.</li>
        <li>Apply seasonal discounts specifically to the selected transport.</li>
    </ul>

    <h3>🐦 Early Bird Discount</h3>
    <p class="abtb_doc_section_intro">
        Early Bird discounts reward passengers who book in advance. You define the qualifying booking window and the corresponding discount percentage.
    </p>
    <ul>
        <li>Enable or disable Early Bird Discount for the transport.</li>
        <li>Define a start and end date for each Early Bird discount period.</li>
        <li>Set the discount percentage for each Early Bird date range.</li>
        <li>Add multiple Early Bird date ranges when needed.</li>
        <li>Provide advance-booking discounts for eligible booking periods.</li>
    </ul>

    <h3>📅 Flexible Discount Periods</h3>
    <p class="abtb_doc_section_intro">
        Both discount types support independent, overlapping, or sequential date ranges.
    </p>
    <ul>
        <li>Configure different discount percentages for different date ranges.</li>
        <li>Add multiple Seasonal Discount periods.</li>
        <li>Add multiple Early Bird Discount periods.</li>
        <li>Manage each discount period independently.</li>
    </ul>

    <h3>⚙️ Smart Discount Control</h3>
    <p class="abtb_doc_section_intro">
        Transport-level settings give you granular control, with global settings available as a fallback.
    </p>
    <ul>
        <li>Disable Seasonal Discount to exclude the transport from seasonal pricing.</li>
        <li>Disable Early Bird Discount to exclude the transport from early bird pricing.</li>
        <li>Transport-level discount settings override global defaults when configured.</li>
        <li>Global discount settings apply when no transport-level discount is configured, if enabled.</li>
    </ul>

    <div class="abtb_doc_callout abtb_doc_callout_note">
        <strong>ℹ️ PRO feature</strong>
        Discount configuration is available only with Transport Booking Pro. The free version does not include seasonal or early bird discount settings.
    </div>

