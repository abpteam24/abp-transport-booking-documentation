        <li>Additional Baggage</li>
        <li>Priority Boarding</li>
        <li>Meal or Food Service</li>
        <li>Wi-Fi Access</li>
        <li>Bicycle or Sports Equipment</li>
        <li>Special Passenger Assistance</li>
        <li>Other Optional Transport Services</li>
    </ul>

