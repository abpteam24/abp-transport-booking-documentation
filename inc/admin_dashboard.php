	<h3>🛣️ Today Trips</h3>
	<p class="abtb_doc_section_intro">
		The main column lists today's journeys. Each journey row shows the transport, route, journey date and
		time, an <strong>Up</strong>/<strong>Return</strong> badge, and a <em>Journey Started</em> badge once the
		trip begins. Availability is shown with <strong>Sold</strong>, <strong>Available</strong>,
		<strong>Total</strong> and <strong>Reserved</strong> counts.
	</p>
	<p class="abtb_doc_section_intro">
		Clicking a journey opens a popup with the journey details: a live <strong>Seat Map</strong> (for seat–plan
		transports) or a <strong>Ticket Type Breakdown</strong> (for ticket–only transports), plus the list of
		bookings for that journey.
	</p>

	<h3>🧾 Recent Orders</h3>
	<p class="abtb_doc_section_intro">
		The <strong>Recent Orders</strong> card shows the latest bookings with two view tabs —
		<strong>Last 10 Orders</strong> and <strong>Today's Orders</strong> — and an
		<strong>All Orders</strong> link that opens the full Order List.
	</p>

	<h3>⚡ Quick Actions (side panel)</h3>
	<p class="abtb_doc_section_intro">
		The sidebar gives one-click shortcuts to the most commonly used screens:
	</p>
	<ul>
		<li><strong>ON/OFF Configuration</strong> — enable or disable plugin features.</li>
		<li><strong>Global Date</strong> — manage global dates.</li>
		<li><strong>Additional Services</strong> and <strong>Client Form</strong> — shown only when the related
			feature switch is enabled.</li>
		<li><strong>Stops Configuration</strong> — manage stops / locations.</li>
		<li><i>PRO</i> — <strong>Partial Payment</strong>, <strong>Global Discount</strong> and
			<strong>Cancel Request</strong> shortcuts appear when the related PRO features are active.</li>
	</ul>

	<h3>🖥️ System Status &amp; Content Breakdown</h3>
	<p class="abtb_doc_section_intro">
		The sidebar also shows a <strong>System Status</strong> card with the current plugin, WordPress, PHP and
		WooCommerce versions, and a <strong>Content Breakdown</strong> card with quick counts of your content by
		type. With <strong>PRO</strong> installed, a license status card is added to the sidebar as well.
	</p>
