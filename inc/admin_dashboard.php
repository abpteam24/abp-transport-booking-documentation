	<p class="abtb_doc_section_intro">
		The top hero section greets the logged-in admin by name, shows today's date and summarizes what is
		happening with the transport booking business today. Two quick buttons are always available:
	</p>
	<ul>
		<li><strong>＋ Add New</strong> — opens the WordPress post editor to create a new transport.</li>
		<li><strong>Orders</strong> — jumps straight to the admin Order List.</li>
	</ul>

	<h3>🔢 Key Performance Cards</h3>
	<p class="abtb_doc_section_intro">
