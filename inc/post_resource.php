        <h2>📚 Resources — Tax, FAQ &amp; Terms &amp; Conditions</h2>
        <p class="abtb_doc_lede">
            The Resources section covers three per-transport settings: Tax calculation (via WooCommerce), Frequently Asked Questions, and Terms &amp; Conditions that passengers must accept before completing a booking.
        </p>
    </div>

    <h3>💰 Tax Configuration</h3>
    <p class="abtb_doc_section_intro">
        Tax calculation for transport bookings is handled entirely through WooCommerce. You control whether tax applies by enabling or disabling WooCommerce Tax in your store settings.
    </p>
    <ul>
        <li>When WooCommerce Tax is enabled, taxes are automatically calculated and applied according to your configured WooCommerce tax rules and product settings.</li>
        <li>When WooCommerce Tax is disabled, no tax is calculated or displayed for transport bookings.</li>
    </ul>

    <div class="abtb_doc_callout abtb_doc_callout_note">
        <strong>ℹ️ WooCommerce dependency</strong>
        Tax display and rates are managed in <em>WooCommerce → Settings → Tax</em>. The plugin itself does not provide a separate tax configuration panel.
    </div>

    <h3>❓ FAQ Configuration</h3>
    <p class="abtb_doc_section_intro">
        The FAQ system lets you display frequently asked questions and answers for each transport. You can define FAQs globally and import them into individual transports, or build transport-specific FAQ lists.
    </p>

    <h3>🌍 Global FAQ</h3>
    <p class="abtb_doc_section_intro">
        From the Global Configuration panel you create and manage a standard set of FAQs that can be reused across transports.
    </p>
    <ul>
        <li>Define global questions and answers.</li>
        <li>Enable or disable the FAQ section globally.</li>
        <li>Maintain a consistent FAQ structure across transports.</li>
    </ul>

    <h3>🚍 Custom Transport-Level FAQ</h3>
    <p class="abtb_doc_section_intro">
        Each individual transport can also have its own custom FAQ configuration, independent of the global set.
    </p>
    <ul>
        <li>Import FAQs from the global configuration.</li>
        <li>Add new FAQs specific to a transport.</li>
        <li>Modify imported questions and answers.</li>
        <li>Remove or reorder FAQs according to transport requirements.</li>
    </ul>

    <h3>🔄 FAQ Import &amp; Customization</h3>
    <ul>
        <li>One-click import from global FAQs.</li>
        <li>Fully editable after import.</li>
        <li>Combine global and custom FAQs when needed.</li>
        <li>Control FAQ order and visibility per transport.</li>
    </ul>

    <h3>📄 Terms &amp; Conditions Configuration</h3>
    <p class="abtb_doc_section_intro">
        The Terms &amp; Conditions system lets you define the policies that passengers must review and accept before completing a transport booking. Like FAQs, terms can be managed globally or per transport.
    </p>

    <h3>🌍 Global Terms &amp; Conditions</h3>
    <p class="abtb_doc_section_intro">
        From the Global Configuration panel you create and manage standard Terms &amp; Conditions that can be reused across transports.
    </p>
    <ul>
        <li>Define global Terms &amp; Conditions content.</li>
        <li>Enable or disable terms acceptance globally.</li>
        <li>Maintain consistent booking policies across transports.</li>
    </ul>

    <h3>🚍 Custom Transport-Level Terms</h3>
    <p class="abtb_doc_section_intro">
        Each individual transport can have its own custom Terms &amp; Conditions configuration when the global terms are not sufficient.
    </p>
    <ul>
        <li>Import Terms &amp; Conditions from the global configuration.</li>
        <li>Add custom terms specific to a transport.</li>
        <li>Modify imported terms when required.</li>
        <li>Replace or customize terms according to transport requirements.</li>
    </ul>

    <h3>🔄 Terms Import &amp; Customization</h3>
    <ul>
        <li>One-click import from global Terms &amp; Conditions.</li>
        <li>Fully editable after import.</li>
        <li>Combine global and custom terms when required.</li>
        <li>Control visibility and acceptance requirements per transport.</li>
    </ul>

