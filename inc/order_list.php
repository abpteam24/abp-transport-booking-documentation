    <h3>✏️ Edit Booking Popup (PRO)</h3>
    <p class="abtb_doc_section_intro">
        Clicking the <strong>✏️</strong> edit button opens the <em>Edit Booking</em> popup with the booking prefilled.
        All prices, seat availability and limits are computed with the exact same logic the customer checkout uses, so
        what you see in the popup is always accurate.
    </p>
    <ul>
        <li><strong>Transport</strong> — switch the booking to any other transport (with its ticket / seat-plan type clearly labelled).</li>
        <li><strong>Route</strong> — pick any boarding → dropping pair for the selected transport, forward or return direction.</li>
        <li><strong>Journey Date</strong> — choose another schedule date for the journey.</li>
        <li><strong>Departure Time</strong> — keeps the resolved start / journey times and total travel duration in sync.</li>
        <li><strong>Pick Up / Drop Off</strong> — change the boarding and destination stops.</li>
        <li><strong>Stock</strong> — for ticket-type transports, set the quantity per ticket type; for seat-plan
            transports, click the interactive seat grid (Available / Selected / Sold legend with per-type prices).</li>
        <li><strong>Passengers</strong> — edit the passenger details captured by the configured client form (when enabled).</li>
        <li><strong>Additional Services</strong> — add or remove extra services with their live remaining counts.</li>
        <li><strong>Billing &amp; Order Status</strong> — name, e-mail, phone and address, plus the WooCommerce order status.</li>
        <li><strong>Price Summary</strong> — line-by-line totals recalculated instantly; a note clarifies that the
            WooCommerce order total itself is not recomputed.</li>
    </ul>

    <h4>✅ Live availability &amp; validation</h4>
    <p class="abtb_doc_section_intro">
        Before a change can be saved, the popup re-checks everything the checkout would:
    </p>
    <ul>
        <li>Seats / tickets already sold or held are excluded — with the booking's <strong>own</strong> stock subtracted
            first, so an unchanged booking never blocks itself.</li>
        <li>Additional service quantities are validated against their remaining counts.</li>
        <li>Routes, journey dates and departure times are validated against the transport schedule.</li>
        <li>The transport <strong>seat type</strong> (seat-plan vs. ticket) cannot be changed on an existing booking —
            the popup warns and the save is blocked.</li>
    </ul>

